// Alex's knowledge base, from the help articles exactly as visitors read them.
// Loads each page in headless Chrome (they render in the browser), keeps the
// article text and writes server/helpArticles.ts. Re-run after changing any
// help article, FAQ or the podcaster guide, then commit:
//   node scripts/build-help-kb.mjs [origin]
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const ORIGIN = (process.argv[2] || "https://www.militaryvoices.ai").replace(/\/+$/, "");
const CHROME = process.env.CHROME || "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
const PAGES = [
  ["/help/studio", "platform"], ["/help/booth", "platform"], ["/help/library", "platform"], ["/help/postify", "platform"], ["/help/podcast", "platform"],
  ["/help/youtube", "platform"], ["/help/zoom", "platform"], ["/help/zoom-story", "platform"], ["/help/smartlink", "platform"], ["/help/guests", "platform"], ["/help/stats", "platform"],
  ["/help/account", "platform"], ["/help/credits", "platform"], ["/faq?all", "marathon"], ["/prepare", "marathon"],
];

const text = (html) => {
  const main = html.match(/<main[\s\S]*?<\/main>/i)?.[0] ?? html;
  return main
    .replace(/<(script|style|svg|nav|header|footer|button)[\s\S]*?<\/\1>/gi, " ")
    .replace(/<\/(p|h[1-6]|li|div|section|tr|summary|details)>/gi, "\n").replace(/<br\s*\/?>/gi, "\n")
    .replace(/<[^>]+>/g, " ")
    .replace(/&amp;/g, "&").replace(/&#x27;|&#39;/g, "'").replace(/&quot;/g, '"').replace(/&nbsp;/g, " ").replace(/&lt;/g, "<").replace(/&gt;/g, ">")
    .replace(/[ \t]+/g, " ").replace(/ ([.,;:!?)])/g, "$1").replace(/\( /g, "(")
    .split("\n").map((l) => l.trim()).filter(Boolean).join("\n");
};

const out = [];
for (const [path, kind] of PAGES) {
  const html = execFileSync(CHROME, ["--headless=new", "--disable-gpu", "--virtual-time-budget=15000", "--dump-dom", ORIGIN + path], { encoding: "utf8", maxBuffer: 50e6, stdio: ["ignore", "pipe", "ignore"] });
  const t = text(html);
  if (t.length < 400) throw new Error(`${path} came back nearly empty (${t.length} chars)`);
  out.push(`=== ${kind === "marathon" ? "THE PODCAST MARATHON (yearly event)" : "MILITARYVOICES.AI PLATFORM"} · ${ORIGIN.replace(/^https?:\/\//, "")}${path.replace(/\?.*$/, "")} ===\n${t}`);
  console.log(path, t.length, "chars");
}
// Alex's answers to the questions people ask most, in the shape every how-to answer takes (PM for Andrew, 24 Nov:
// "Yes, fix Alex"): at most 3 short numbered steps, buttons and tabs in **bold** exactly as the screen says them,
// no jargon, about 60 words, and a [[GO:<page>]] token the chat turns into a "Take me there" button
// ([[READ:<help article>]] for "Read the full guide"). Never a path in the words. Test: script/alex-answers.test.ts.
const QUICK = [
  { q: "How do I get my podcast on Spotify and Apple?", a: "Two steps, about 5 minutes:\n1. Open your show, then **Directories**.\n2. Press **List it** next to Apple, then next to Spotify.\nIf anything's missing, like a cover or a description, that screen tells you first.\n[[GO:directories]]" },
  { q: "How do I make clips from an episode?", a: "1. Open **Pōstify**.\n2. Drop in your video, or pick one from your Library.\n3. Press **Start Pōstify**.\nYour captioned clips are ready in a few minutes. Your first episode is free.\n[[GO:postify]]" },
  { q: "Where are my Marathon recording and clips?", a: "They're in your **Library**. Open the Marathon recording to see its clips and files.\n[[GO:library]]" },
  { q: "How do I connect Zoom?", a: "1. Open **Integrations**.\n2. Press **Connect Zoom** and sign in to Zoom.\n3. Switch on **Auto-import new**.\nYour cloud recordings then come into your Library by themselves.\n[[GO:zoom]]" },
  { q: "How do I add a new episode?", a: "1. Open your show and press **New episode**.\n2. Pick a recording from your Library, or drop in a file.\n3. Add a title, then publish it now or schedule it.\n[[GO:new-episode]]" },
  { q: "How do I set up my SmartLink?", a: "1. Open **SmartLink**.\n2. Pick the name for your link.\n3. Work down the steps. Everything saves as you go.\n[[GO:smartlink]]" },
  { q: "How do I invite a guest to my show?", a: "1. Open your show, then **Invite a guest**.\n2. Add their name and email, when, and where you'll record.\n3. Press **Send the invitation**.\n[[GO:guest-invite]]" },
];

const body = out.join("\n\n").replace(/`/g, "'").replace(/\$\{/g, "$ {");
writeFileSync("server/helpArticles.ts", `// Generated by scripts/build-help-kb.mjs from the live help articles, FAQ and podcaster guide.\n// Don't edit by hand: change the article, deploy, and re-run the script.\nexport const HELP_ARTICLES = \`\n${body}\n\`;\n\n/** Alex's answers to the most-asked how-tos, in the house shape (see QUICK in scripts/build-help-kb.mjs). */\nexport const QUICK_ANSWERS: { q: string; a: string }[] = ${JSON.stringify(QUICK, null, 2)};\n`);
console.log("wrote server/helpArticles.ts", body.length, "chars");
